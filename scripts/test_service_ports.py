# Held for the process lifetime on purpose. Several detectors read files at DETECTION time
# rather than at Workspace construction, so a tree removed when a context manager exits is a
# tree they see as empty - and an empty tree is INDETERMINATE, which reads as "no finding".
# The first draft of this file did exactly that and reported nine passing controls that had
# never been given anything to look at.
_TREES: list[tempfile.TemporaryDirectory] = []


def run(overrides: dict[str, str] | None = None, drop: tuple[str, ...] = ()):
    holder = tempfile.TemporaryDirectory()
    _TREES.append(holder)
    root = pathlib.Path(holder.name)
    tree = dict(BASE_TREE)
    for key in drop:
        tree.pop(key, None)
    tree.update(overrides or {})
    for rel, text in tree.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return m.Workspace(root)


