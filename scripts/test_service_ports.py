# THE TABLE-CONFUSION HAZARD, and the reason this file has a two-table fixture at all.
#
# ports.generated.go holds clusterPorts and localPorts in the same shape. A detector matching
# entries anywhere in the file collects both, and the last write wins -- so SP-0002 would
# compare the manifests against the LOCAL table. That is green while a service is unmigrated
# and the two tables agree, and it goes red the moment one migrates, with a finding shaped
# exactly like the outage SP-0002 exists to catch. Here the local table alone carries the old
# numbers and the manifests and cluster table are both migrated, so reading the wrong one is
# the only way to produce a finding.
ws = run({"shared/platform-shared-go/platform/servicediscovery/ports.generated.go":
          registry_go(cluster={"alpha-service": (8080, 50051), "beta-service": (4003, 50061)},
                      local={"alpha-service": (4002, 50060), "beta-service": (4003, 50061)}),
          "infra/inboxxhq-infra/services/alpha-service/base/service.yaml":
          service_yaml("alpha-service", 8080, 50051, 9464),
          "infra/inboxxhq-infra/services/alpha-service/overlays/dev/deployment.yaml":
          deployment_yaml([8080, 50051, 9464], 8080, {"PORT": 8080})})
expect(ws.registry["alpha-service"] == (8080, 50051),
       f"SP-0002: the CLUSTER table must be the one parsed; got {ws.registry.get('alpha-service')}")
expect(ws.local_registry["alpha-service"] == (4002, 50060),
       f"SP-0002: the local table must be read separately; got {ws.local_registry.get('alpha-service')}")
finding = m.k8s_ports_match_registry(ws)
expect(finding.count == 0,
       f"SP-0002: a migrated service must agree with the cluster table, not the local one; "
       f"got {finding.details}")

