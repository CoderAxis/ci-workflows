#!/usr/bin/env python3
"""Precision/recall and wiring tests for SP-0001..SP-0007.

Every detector is exercised against a synthetic workspace in both directions: a conformant
tree must not produce a finding, and a tree carrying exactly the defect the control names
must produce one. A control that only ever passes is indistinguishable from a control that
cannot fail, which is the failure RFC-0007 §10 records about the previous Dockerfile check.
"""

from __future__ import annotations

