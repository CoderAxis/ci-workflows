HERE = pathlib.Path(__file__).resolve().parent
CHECKER = HERE / "check-service-ports.py"
CONTROLS = HERE.parent / "controls" / "service-ports.yaml"
FAILURES: list[str] = []


def load_checker():
    spec = importlib.util.spec_from_file_location("check_service_ports", CHECKER)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


m = load_checker()


def expect(condition: bool, message: str) -> None:
    if not condition:
        FAILURES.append(message)


# Two tables of identical shape, which is the point: the checker must read the CLUSTER one.
# The local values are deliberately different from the cluster ones for beta-service, so a
# detector reading the wrong table produces a visible finding rather than an accidental pass.
def registry_go(cluster: dict[str, tuple[int, int]] | None = None,
                local: dict[str, tuple[int, int]] | None = None) -> str:
    cluster = cluster if cluster is not None else {"alpha-service": (4002, 50060),
                                                  "beta-service": (4003, 50061)}
    local = local if local is not None else {"alpha-service": (4002, 50060),
                                             "beta-service": (4003, 50061)}

    # clusterListeners records membership, not a per-service port: a non-zero
    # tuple entry means that listener exists and answers on the §4.1 constant.
    def listeners(entries):
        rows = "".join(
            f'\t"{svc}": {{HTTP: {str(h != 0).lower()}, GRPC: {str(g != 0).lower()}}},\n'
            for svc, (h, g) in sorted(entries.items())
        )
        return f"var clusterListeners = map[string]listeners{{\n{rows}}}\n"

    def table(name, entries):
        rows = "".join(f'\t"{svc}": {{HTTPPort: {h}, GRPCPort: {g}}},\n'
                       for svc, (h, g) in sorted(entries.items()))
        return f"var {name} = map[string]ServiceEndpoint{{\n{rows}}}\n"

    return ("// Code generated by internal/gen/serviceports. DO NOT EDIT.\n"
            "package servicediscovery\n\n"
            + listeners(cluster) + "\n" + table("localPorts", local))


REGISTRY = registry_go()


def service_yaml(name: str, http: int, grpc: int, metrics: int, target_http: int | None = None,
                 extra: list[dict] | None = None):
    ports = [
        {"name": "http", "port": http, "targetPort": target_http or http},
        {"name": "grpc", "port": grpc, "targetPort": grpc},
        {"name": "metrics", "port": metrics, "targetPort": metrics},
    ]
    return yaml.safe_dump({
        "apiVersion": "v1", "kind": "Service",
        "metadata": {"name": f"inboxxhq-{name}"},
        "spec": {"ports": ports + (extra or [])},
    })


def deployment_yaml(ports: list[int], probe: int, env: dict[str, int] | None = None):
    container = {
        "name": "app",
        "ports": [{"containerPort": p} for p in ports],
        "livenessProbe": {"httpGet": {"path": "/health/live", "port": probe}},
        "readinessProbe": {"httpGet": {"path": "/health/ready", "port": probe}},
    }
    if env:
        container["env"] = [{"name": k, "value": str(v)} for k, v in env.items()]
    return yaml.safe_dump({
        "apiVersion": "apps/v1", "kind": "Deployment",
        "metadata": {"name": "app"},
        "spec": {"template": {"spec": {"containers": [container]}}},
    })


def monitor_yaml(name: str, port):
    return yaml.safe_dump({
        "apiVersion": "monitoring.coreos.com/v1", "kind": "ServiceMonitor",
        "metadata": {"name": f"inboxxhq-{name}-metrics"},
        "spec": {"endpoints": [{"port": port, "path": "/metrics"}]},
    })


